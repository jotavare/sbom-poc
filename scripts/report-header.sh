#!/usr/bin/env bash
# Prints the header of the combined SBOM report: commit, time, tool versions and
# the image digests, so a report can always be traced to what produced it.
#
# Usage: scripts/report-header.sh [out-root]
set -euo pipefail
export LC_ALL=C

ROOT="${1:-sbom}"
commit="$(git rev-parse HEAD 2> /dev/null || echo unknown)"
dirty=""
git diff --quiet HEAD 2> /dev/null || dirty=" (+ uncommitted changes)"

echo "# SBOM report: generators, validation, licences, quality"
echo
echo "_Generated by \`make report\`. Not committed: CI publishes it as the \`sbom-report\` artifact._"
echo
echo "| | |"
echo "|---|---|"
echo "| Commit | \`$commit\`$dirty |"
echo "| Generated | $(date -u +%Y-%m-%dT%H:%M:%SZ) |"
# tool images pinned in the scripts (name:version, digest omitted for brevity)
grep -hoE '(anchore/syft|aquasec/trivy|anchore/grant|interlynk-io/sbomqs|cyclonedx/cyclonedx-cli|docker/buildkit-syft-scanner|moby/buildkit):[A-Za-z0-9._-]+' scripts/*.sh \
  | sort -u | sed 's/^/| Tool | `/; s/$/` |/'
grep -hoE 'CDXGEN_VERSION:-[^}]+' scripts/generate-sbom.sh | sed 's/CDXGEN_VERSION:-/| Tool | `cdxgen /; s/$/` (release binary) |/'
grep -hoE 'SPDX_TOOLS_VERSION="[^"]+' scripts/validate-sbom.sh | sed 's/SPDX_TOOLS_VERSION="/| Tool | `spdx-tools /; s/$/` |/'
for f in "$ROOT"/*/artifact.json; do
  [[ -s "$f" ]] && jq -r '"| Image (\(.app)) | `\(.image)@\(.index_digest)` |"' "$f"
done
echo
