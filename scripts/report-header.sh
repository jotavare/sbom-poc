#!/usr/bin/env bash
# Prints the header of the combined SBOM report: commit, time, tool versions and
# the image digests, so a report can always be traced to what produced it.
#
# Usage: scripts/report-header.sh [out-root]
set -euo pipefail
export LC_ALL=C

ROOT="${1:-sbom}"
commit="$(git rev-parse HEAD 2> /dev/null || echo unknown)"
dirty=""
git diff --quiet HEAD 2> /dev/null || dirty=" (+ uncommitted changes)"

echo "# SBOM report: stages, generators, validation, vulnerabilities, licences, quality"
echo
echo "_Generated by \`make report\`. Not committed: CI publishes it as the \`sbom-report\` artifact._"
echo
echo "| | |"
echo "|---|---|"
echo "| Commit | \`$commit\`$dirty |"
echo "| Generated | $(date -u +%Y-%m-%dT%H:%M:%SZ) |"
# tool images pinned in the scripts (name:version, digest omitted for brevity)
grep -hoE '(anchore/syft|anchore/grype|google/osv-scanner|aquasec/trivy|anchore/grant|interlynk-io/sbomqs|cyclonedx/cyclonedx-cli|docker/buildkit-syft-scanner|moby/buildkit):[A-Za-z0-9._-]+' scripts/*.sh \
  | sort -u | sed 's/^/| Tool | `/; s/$/` |/'
grep -hoE 'CDXGEN_VERSION:-[^}]+' scripts/generate-sbom.sh | sed 's/CDXGEN_VERSION:-/| Tool | `cdxgen /; s/$/` (release binary) |/'
grep -hoE 'SPDX_TOOLS_VERSION="[^"]+' scripts/validate-sbom.sh | sed 's/SPDX_TOOLS_VERSION="/| Tool | `spdx-tools /; s/$/` |/'
for f in "$ROOT"/*/artifact.json; do
  [[ -s "$f" ]] && jq -r '"| Image (\(.app)) | `\(.image)@\(.index_digest)` |"' "$f"
done
echo
cat <<'EOF'
## How to read this report

Each app's section follows the SBOM stages defined by CISA (*Types of SBOM Documents*) and recorded in each CycloneDX SBOM as `metadata.lifecycles` (CISA's "Generation Context"). Background and sources: `docs/SBOM-TYPES.md`.

```mermaid
flowchart LR
  S["1 Source<br/>pre-build<br/>what the repo declares"] --> B["2 Build<br/>build<br/>what the build resolved"]
  B --> I["3 Analyzed<br/>post-build<br/>what is in the image"]
  I --> R["4 Runtime<br/>operations<br/>what actually runs"]
```

| Stage | Files | Made by | Typical finding |
|---|---|---|---|
| 1 Source | `<gen>-source.*` | Syft, Trivy, cdxgen on the app directory | dev/test dependencies are declared too |
| 2 Build | `native-build.cdx.json`, `buildkit-image.spdx.json` | the package manager inside the Docker build; BuildKit's attestation | the reference dependency tree |
| 3 Analyzed | `<gen>-image.*`, `views/*` | Syft, Trivy, cdxgen on the built image | base-image content the build never installed (e.g. npm) |
| 4 Runtime | `runtime.cdx.json` | the app run under strace + probes | most shipped packages never run |

Then, per app: validation against the specs, vulnerabilities (Grype, Trivy, OSV-Scanner on the SBOMs, with the gate), licence policy, quality scores, and (when run) ScanCode.

EOF
